"""Write ts/src/tables.ts and ts/src/data/colors.json from the Python tables (dev-time only).

    python tools/ts_tables.py

The TypeScript port reads its key names, defaults, aliases, descriptions, value tables, the ECharts patch allowlist
and the colour data from these generated files, so the two implementations cannot drift apart. Sets become sorted
arrays. Do not edit the output; change the Python tables and run this again.
"""
import json
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from plotkit import charts, colors, core, echarts  # noqa: E402

OUT = ROOT / "ts" / "src"


def norm(v):
    if isinstance(v, (set, frozenset)):
        return sorted(v)
    if isinstance(v, tuple):
        return [norm(x) for x in v]
    if isinstance(v, dict):
        return {str(k): norm(x) for k, x in v.items()}
    if isinstance(v, list):
        return [norm(x) for x in v]
    return v


TABLES = {
    # plotkit.core (curves)
    "VERSION": core.__version__,
    "DEFAULTS": core.DEFAULTS, "TGA_PRESET": core.TGA_PRESET, "SCHEMA_DOC": core.SCHEMA_DOC,
    "EXAMPLE_SPEC": core.EXAMPLE_SPEC, "ANNOT_KEYS": core.ANNOT_KEYS, "ANNOT_TYPES": core.ANNOT_TYPES,
    "ENGINES": core.ENGINES, "TOP_ALIASES": core.TOP_ALIASES, "AXIS_ALIASES": core.AXIS_ALIASES,
    "ANNOT_ALIASES": core.ANNOT_ALIASES, "KOREAN_COLORS": core.KOREAN_COLORS, "LINESTYLES": core.LINESTYLES,
    "LINESTYLE_NAMES": core.LINESTYLE_NAMES, "LEGEND_PLACES": core.LEGEND_PLACES, "KOREAN_PLACES": core.KOREAN_PLACES,
    "COMBINE_COLORS": core.COMBINE_COLORS, "FORMATS": core.FORMATS,
    # plotkit.charts
    "CHART_KINDS": charts.KINDS, "CHART_KIND_ALIASES": charts.KIND_ALIASES, "CHART_AGGS": charts.AGGS,
    "CHART_AGG_ALIASES": charts.AGG_ALIASES, "CHART_PERIODS": charts.PERIODS, "CHART_PERIOD_NAMES": charts.PERIOD_NAMES,
    "CHART_PALETTE": charts.PALETTE, "CHART_GRAYS": charts.GRAYS, "CHART_HIGHLIGHT_GRAY": charts.HIGHLIGHT_GRAY,
    "CHART_AXIS_KEYS": charts.AXIS_KEYS, "CHART_TOP_KEYS": charts.TOP_KEYS, "CHART_TOP_ALIASES": charts.TOP_ALIASES,
    "CHART_AXIS_EXTRA_ALIASES": charts.AXIS_EXTRA_ALIASES, "CHART_SCHEMA_DOC": charts.SCHEMA_DOC,
    "CHART_KEYS": charts.CHART_KEYS,
    # plotkit.echarts (the patch allowlist)
    "PATCH_ALLOWED": echarts.ALLOWED, "PATCH_GRAPHIC_TYPES": echarts.GRAPHIC_TYPES,
    "PATCH_ALIASES": echarts.PATCH_ALIASES, "PATCH_MARK_ITEM": echarts._MARK_ITEM,
}


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    lines = ["// Generated by tools/ts_tables.py from the Python tables. Do not edit.", "/* eslint-disable */", ""]
    for name, value in TABLES.items():
        lines.append(f"export const {name} = {json.dumps(norm(value), ensure_ascii=False, indent=1)} as const;")
        lines.append("")
    (OUT / "tables.ts").write_text("\n".join(lines), encoding="utf-8")
    (OUT / "data").mkdir(exist_ok=True)
    shutil.copyfile(colors.DATA, OUT / "data" / "colors.json")
    print(f"wrote {OUT / 'tables.ts'} and {OUT / 'data' / 'colors.json'}")


if __name__ == "__main__":
    main()
